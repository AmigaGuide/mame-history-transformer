"""Compare individual Gaming History audit findings across releases."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from mht.utils.io import sha256_file, write_json


def finding_key(finding: dict) -> str:
    """Return a stable identity for an exact source observation."""
    identity = {
        "rule_id": finding["rule_id"],
        "machine": finding["machine"],
        "section": finding["section"],
        "source_text": finding["source_text"],
        "value": finding.get("value"),
    }

    encoded = json.dumps(
        identity,
        sort_keys=True,
        ensure_ascii=False,
    ).encode("utf-8")

    return hashlib.sha256(encoded).hexdigest()


def _revision_snapshot_path(releases_dir: Path, version: str) -> Path:
    """Locate a lettered or base GH audit under its base MAME release."""
    match = re.fullmatch(r"(\d{4})([a-z]?)", version)
    if not match:
        raise ValueError(f"Invalid GH revision identifier: {version!r}")
    base = match.group(1)
    archive_stem = f"history{int(base)}{match.group(2)}"
    return releases_dir / base / "summaries" / "gh_audit_revisions" / f"{archive_stem}.json"


def _load_revision_audit(path: Path, version: str) -> dict:
    """Validate the stored wrapper; return the nested audit without altering it."""
    snapshot = json.loads(path.read_text(encoding="utf-8"))
    match = re.fullmatch(r"(\d{4})([a-z]?)", version)
    if match is None:
        raise ValueError(f"Invalid GH revision identifier: {version!r}")
    base = match.group(1)
    expected_archive = f"history{int(base)}{match.group(2)}.zip"
    if (not isinstance(snapshot, dict)
            or snapshot.get("schema_id") != "mht.gh.audit_snapshot"
            or snapshot.get("release") != base
            or snapshot.get("revision_archive") != expected_archive):
        raise ValueError(f"GH audit snapshot does not match {version}: {path}")
    audit = snapshot.get("audit")
    if (not isinstance(audit, dict)
            or audit.get("schema_id") != "mht.history.audit_findings"
            or audit.get("release") != base
            or not isinstance(audit.get("detectors"), dict)
            or not isinstance(audit.get("findings"), list)):
        raise ValueError(f"Invalid nested GH audit in {path}")
    inputs = (audit.get("provenance") or {}).get("inputs")
    if (not isinstance(inputs, list) or len(inputs) != 1
            or not isinstance(inputs[0], dict)
            or inputs[0].get("zip_archive") != expected_archive
            or inputs[0].get("zip_member") != snapshot.get("source_member")):
        raise ValueError(f"GH snapshot source provenance mismatch: {path}")
    return audit


def compare_history_revision_snapshots(releases_dir: Path, versions: list[str]) -> dict:
    """Compare immutable GH ZIP revisions without rerunning the parser."""
    return compare_history_audits(releases_dir, versions, revision_snapshots=True)


def compare_history_audits(
    releases_dir: Path,
    versions: list[str],
    *,
    revision_snapshots: bool = False,
) -> dict:
    """Compare findings from releases or immutable GH revision snapshots."""

    if not versions:
        raise ValueError("No releases supplied for comparison")

    if len(set(versions)) != len(versions):
        raise ValueError("Duplicate release identifiers supplied")

    def release_order(version: str) -> tuple[int, int]:
        """Order MAME-aligned releases and optional GH letter revisions."""
        if not isinstance(version, str):
            raise ValueError(f"Invalid release identifier: {version!r}")

        match = re.fullmatch(r"(\d{4})([a-z]?)", version)
        if not match:
            raise ValueError(f"Invalid release identifier: {version!r}")

        number = int(match.group(1))
        revision = match.group(2)

        return (
            number,
            ord(revision) - ord("a") + 1 if revision else 0,
        )

    if versions != sorted(versions, key=release_order):
        raise ValueError("Releases must be supplied in chronological order")

    # These reports must have been generated by comparable detectors.
    expected_detectors = None
    findings_by_key = {}

    for version in versions:
        audit_path = (
            _revision_snapshot_path(releases_dir, version)
            if revision_snapshots else
            releases_dir / version / "summaries" / "history_audit_findings.json"
        )
        if not audit_path.is_file():
            raise FileNotFoundError(
                f"Missing GH audit report for release {version}: {audit_path}"
            )
        audit = (_load_revision_audit(audit_path, version)
                 if revision_snapshots else
                 json.loads(audit_path.read_text(encoding="utf-8")))
        if audit.get("schema_id") != "mht.history.audit_findings":
            raise ValueError(f"Unexpected audit schema in {audit_path}")
        expected_release = version[:4] if revision_snapshots else version
        if audit.get("release") != expected_release:
            raise ValueError(f"Release mismatch in {audit_path}")

        detectors = audit.get("detectors", {})

        if expected_detectors is None:
            expected_detectors = detectors
        elif detectors != expected_detectors:
            raise ValueError(
                f"Detector definitions differ in release {version}"
            )

        for finding in audit.get("findings", []):
            key = finding_key(finding)

            if key not in findings_by_key:
                findings_by_key[key] = {
                    "finding_key": key,
                    "rule_id": finding["rule_id"],
                    "machine": finding["machine"],
                    "section": finding["section"],
                    "source_text": finding["source_text"],
                    "value": finding.get("value"),
                    "occurrences": {},
                }

            occurrences = findings_by_key[key]["occurrences"]
            occurrences[version] = occurrences.get(version, 0) + 1

    histories = []

    for finding in findings_by_key.values():
        occurrences = finding["occurrences"]

        present = [
            version
            for version in versions
            if occurrences.get(version, 0) > 0
        ]

        first_observed = present[0]
        last_observed = present[-1]

        first_absent = None
        reappeared = []
        transitions = []

        seen_present = False
        absent_since_present = False

        for version in versions:
            is_present = occurrences.get(version, 0) > 0

            if is_present:
                if seen_present and absent_since_present:
                    reappeared.append(version)
                    transitions.append({
                        "release": version,
                        "event": "reappeared",
                    })

                seen_present = True
                absent_since_present = False

            elif seen_present:
                if not absent_since_present:
                    transitions.append({
                        "release": version,
                        "event": "disappeared",
                    })

                if first_absent is None:
                    first_absent = version

                absent_since_present = True

        finding["first_observed"] = first_observed
        finding["last_observed"] = last_observed
        finding["first_absent"] = first_absent
        finding["reappeared"] = reappeared
        finding["transitions"] = transitions
        finding["present_in_latest"] = bool(
            occurrences.get(versions[-1], 0)
        )

        histories.append(finding)

    histories.sort(
        key=lambda item: (
            item["machine"],
            item["rule_id"],
            item["finding_key"],
        )
    )

    return {
        "schema_id": "mht.history.audit_comparison",
        "schema_version": "1.0.0",
        "releases_compared": versions,
        "detectors": expected_detectors,
        "findings": histories,
    }


def write_history_comparison(
    releases_dir: Path,
    versions: list[str],
    output_path: Path,
    *,
    revision_snapshots: bool = False,
) -> bool:
    """Write a historical comparison with source audit provenance."""

    comparison = compare_history_audits(
        releases_dir,
        versions,
        revision_snapshots=revision_snapshots,
    )

    source_reports = []

    for version in versions:
        audit_path = (
            _revision_snapshot_path(releases_dir, version)
            if revision_snapshots else
            releases_dir / version / "summaries" / "history_audit_findings.json"
        )

        source_reports.append({
            "release": version,
            "path": audit_path.as_posix(),
            "sha256": sha256_file(audit_path),
        })

    comparison["provenance"] = {
        "source_audits": source_reports,
    }

    return write_json(
        output_path,
        comparison,
        sort_keys=False,
    )
