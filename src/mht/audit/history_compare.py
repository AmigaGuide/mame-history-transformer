"""Compare individual Gaming History audit findings across releases."""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

from mht.utils.io import sha256_file, write_json


def finding_key(finding: dict) -> str:
    """Return a stable identity for an exact source observation."""
    identity = {
        "rule_id": finding["rule_id"],
        "machine": finding["machine"],
        "section": finding["section"],
        "source_text": finding["source_text"],
        "value": finding.get("value"),
    }

    encoded = json.dumps(
        identity,
        sort_keys=True,
        ensure_ascii=False,
    ).encode("utf-8")

    return hashlib.sha256(encoded).hexdigest()


def compare_history_audits(
    releases_dir: Path,
    versions: list[str],
) -> dict:
    """Compare findings from a sequence of completed GH audits."""

    if not versions:
        raise ValueError("No releases supplied for comparison")

    if len(set(versions)) != len(versions):
        raise ValueError("Duplicate release identifiers supplied")

    def release_order(version: str) -> tuple[int, int]:
        """Order MAME-aligned releases and optional GH letter revisions."""
        if not isinstance(version, str):
            raise ValueError(f"Invalid release identifier: {version!r}")

        match = re.fullmatch(r"(\d{4})([a-z]?)", version)
        if not match:
            raise ValueError(f"Invalid release identifier: {version!r}")

        number = int(match.group(1))
        revision = match.group(2)

        return (
            number,
            ord(revision) - ord("a") + 1 if revision else 0,
        )

    if versions != sorted(versions, key=release_order):
        raise ValueError("Releases must be supplied in chronological order")

    # These reports must have been generated by comparable detectors.
    expected_detectors = None
    findings_by_key = {}

    for version in versions:
        audit_path = (
            releases_dir
            / version
            / "summaries"
            / "history_audit_findings.json"
        )

        if not audit_path.is_file():
            raise FileNotFoundError(
                f"Missing GH audit report for release {version}: "
                f"{audit_path}"
            )

        audit = json.loads(audit_path.read_text(encoding="utf-8"))

        if audit.get("schema_id") != "mht.history.audit_findings":
            raise ValueError(f"Unexpected audit schema in {audit_path}")

        if audit.get("release") != version:
            raise ValueError(f"Release mismatch in {audit_path}")

        detectors = audit.get("detectors", {})

        if expected_detectors is None:
            expected_detectors = detectors
        elif detectors != expected_detectors:
            raise ValueError(
                f"Detector definitions differ in release {version}"
            )

        for finding in audit.get("findings", []):
            key = finding_key(finding)

            if key not in findings_by_key:
                findings_by_key[key] = {
                    "finding_key": key,
                    "rule_id": finding["rule_id"],
                    "machine": finding["machine"],
                    "section": finding["section"],
                    "source_text": finding["source_text"],
                    "value": finding.get("value"),
                    "occurrences": {},
                }

            occurrences = findings_by_key[key]["occurrences"]
            occurrences[version] = occurrences.get(version, 0) + 1

    histories = []

    for finding in findings_by_key.values():
        occurrences = finding["occurrences"]

        present = [
            version
            for version in versions
            if occurrences.get(version, 0) > 0
        ]

        first_observed = present[0]
        last_observed = present[-1]

        first_absent = None
        reappeared = []
        transitions = []

        seen_present = False
        absent_since_present = False

        for version in versions:
            is_present = occurrences.get(version, 0) > 0

            if is_present:
                if seen_present and absent_since_present:
                    reappeared.append(version)
                    transitions.append({
                        "release": version,
                        "event": "reappeared",
                    })

                seen_present = True
                absent_since_present = False

            elif seen_present:
                if not absent_since_present:
                    transitions.append({
                        "release": version,
                        "event": "disappeared",
                    })

                if first_absent is None:
                    first_absent = version

                absent_since_present = True

        finding["first_observed"] = first_observed
        finding["last_observed"] = last_observed
        finding["first_absent"] = first_absent
        finding["reappeared"] = reappeared
        finding["transitions"] = transitions
        finding["present_in_latest"] = bool(
            occurrences.get(versions[-1], 0)
        )

        histories.append(finding)

    histories.sort(
        key=lambda item: (
            item["machine"],
            item["rule_id"],
            item["finding_key"],
        )
    )

    return {
        "schema_id": "mht.history.audit_comparison",
        "schema_version": "1.0.0",
        "releases_compared": versions,
        "detectors": expected_detectors,
        "findings": histories,
    }


def write_history_comparison(
    releases_dir: Path,
    versions: list[str],
    output_path: Path,
) -> bool:
    """Write a historical comparison with source audit provenance."""

    comparison = compare_history_audits(
        releases_dir,
        versions,
    )

    source_reports = []

    for version in versions:
        audit_path = (
            releases_dir
            / version
            / "summaries"
            / "history_audit_findings.json"
        )

        source_reports.append({
            "release": version,
            "path": audit_path.as_posix(),
            "sha256": sha256_file(audit_path),
        })

    comparison["provenance"] = {
        "source_audits": source_reports,
    }

    return write_json(
        output_path,
        comparison,
        sort_keys=False,
    )
